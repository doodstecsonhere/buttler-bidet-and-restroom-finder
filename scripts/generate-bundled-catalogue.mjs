// Generator for the PWA's offline restroom catalogue bundle.
//
// The bundled offline catalogue must never be a second, independently
// maintained dataset: it is generated from the same owner-approved canonical
// CSV that feeds the D1 read model, plus the ordered post-base reconciliation
// operations (Stage 14K.1), through the exact projection applied by
// functions/api/restrooms.ts. Regenerate it whenever the canonical dataset is
// re-imported OR a reconciliation is recorded, so online and offline data
// cannot silently diverge.
//
// Usage:
//   node scripts/generate-bundled-catalogue.mjs --write   regenerate lib/restroom-bundle.ts
//   node scripts/generate-bundled-catalogue.mjs --check   fail if the bundle is stale

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

import {
  loadCanonicalDataset,
  applyCanonicalReconciliations,
  selectActiveCanonicalRows,
  validateDataset,
} from "./import-canonical.mjs";

const OUTPUT_FILE = new URL("../lib/restroom-bundle.ts", import.meta.url);

// Mirrors SELECT_PUBLIC_CANONICAL_LOCATIONS + toPublicRestroom in
// functions/api/restrooms.ts. The raw CSV rows all carry the seed default
// record_status='candidate'; a canonical row only leaves the active set when
// an explicit reconciliation `suppress` operation marks it (mirroring the API
// WHERE record_status <> 'rejected' filter over D1 state). This is NOT a
// global rejected-row filter over arbitrary data — see
// selectActiveCanonicalRows in scripts/import-canonical.mjs.
export function projectCanonicalRows(canonical) {
  return [...canonical]
    .sort((left, right) =>
      left.Canonical_Location_ID < right.Canonical_Location_ID ? -1 : 1,
    )
    .map((row) => ({
      id: row.Canonical_Location_ID,
      name: row.Name,
      latitude: Number(row.Latitude),
      longitude: Number(row.Longitude),
      address: row.Address === "" ? null : row.Address,
      access: row.Access,
      fee: row.Fee,
      bidet: row.Bidet_Presence === "Yes",
      bidet_evidence: row.Bidet_Verification,
    }));
}

export function generateBundledCatalogue(canonical) {
  const rows = projectCanonicalRows(canonical);
  const body = rows.map((row) => `  ${JSON.stringify(row)}`).join(",\n");
  return [
    "// Generated by scripts/generate-bundled-catalogue.mjs from the owner-approved",
    "// canonical dataset plus the recorded post-base reconciliations",
    "// (attached_assets/buttler_canonical_reconciliations.csv); do not edit by",
    "// hand. After any dataset re-import or new reconciliation operation run:",
    "//   node scripts/generate-bundled-catalogue.mjs --write",
    "",
    "import type { Restroom } from \"./restroom-data.ts\";",
    "",
    `// Offline fallback catalogue: the public projection of the effective`,
    `// active canonical dataset (${rows.length} locations after reconciliations).`,
    "// Discovery candidates with unknown restroom or bidet presence are",
    "// intentionally included; unknown is never coerced.",
    "export const BUNDLED_RESTROOMS: Restroom[] = [",
    `${body},`,
    "];",
    "",
  ].join("\n");
}

// The effective ACTIVE catalogue: raw CSV dataset + ordered reconciliation
// operations, with suppressed rows excluded. validateDataset runs against the
// full effective dataset (lineage rows included), so every provenance,
// survey-coupling, and Source_Count invariant is proven to still hold after
// the reconciliations are applied.
export function loadEffectiveActiveCatalogue() {
  const dataset = loadCanonicalDataset();
  validateDataset(dataset);
  const effective = applyCanonicalReconciliations(dataset);
  validateDataset(effective);
  return selectActiveCanonicalRows(effective);
}

const mode = process.argv[2];
const isEntry =
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isEntry && (mode === "--write" || mode === "--check")) {
  const active = loadEffectiveActiveCatalogue();
  const generated = generateBundledCatalogue(active);

  if (mode === "--write") {
    writeFileSync(OUTPUT_FILE, generated, "utf8");
    console.log(
      `BUNDLED_CATALOGUE_WRITTEN rows=${active.length}`,
    );
  } else {
    const current = existsSync(OUTPUT_FILE)
      ? readFileSync(OUTPUT_FILE, "utf8").replaceAll("\r\n", "\n")
      : "";
    if (current !== generated) {
      throw new Error(
        "lib/restroom-bundle.ts is stale; run: node scripts/generate-bundled-catalogue.mjs --write",
      );
    }
    console.log(
      `BUNDLED_CATALOGUE_CURRENT rows=${active.length}`,
    );
  }
} else if (isEntry) {
  throw new Error("Use --write or --check");
}
